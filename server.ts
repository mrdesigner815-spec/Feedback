// In-memory audio cache to prevent redundant API calls
const audioCache = new Map<string, string>();

const getAiClient = () => {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) {
    throw new Error('GEMINI_API_KEY is not configured in environment');
  }
  return new GoogleGenAI({
    apiKey,
    httpOptions: {
      headers: {
        'User-Agent': 'aistudio-build',
      },
    },
  });
};

// Generates a valid audible 24kHz 16-bit WAV buffer as a fallback
function createFallbackWav(durationSeconds = 2.5, frequency = 440): Buffer {
  const sampleRate = 24000;
  const numChannels = 1;
  const bitsPerSample = 16;
  const numSamples = Math.floor(sampleRate * durationSeconds);
  const blockAlign = (numChannels * bitsPerSample) / 8;
  const byteRate = sampleRate * blockAlign;
  const dataSize = numSamples * blockAlign;
  const headerSize = 44;
  const buffer = Buffer.alloc(headerSize + dataSize);

  // RIFF identifier
  buffer.write('RIFF', 0);
  buffer.writeUInt32LE(36 + dataSize, 4);
  buffer.write('WAVE', 8);

  // 'fmt ' chunk
  buffer.write('fmt ', 12);
  buffer.writeUInt32LE(16, 16);
  buffer.writeUInt16LE(1, 20); // PCM = 1
  buffer.writeUInt16LE(numChannels, 22);
  buffer.writeUInt32LE(sampleRate, 24);
  buffer.writeUInt32LE(byteRate, 28);
  buffer.writeUInt16LE(blockAlign, 32);
  buffer.writeUInt16LE(bitsPerSample, 34);

  // 'data' chunk
  buffer.write('data', 36);
  buffer.writeUInt32LE(dataSize, 40);

  // Harmonic educator tone
  for (let i = 0; i < numSamples; i++) {
    const t = i / sampleRate;
    const envelope = Math.sin((Math.PI * i) / numSamples);
    const sample =
      0.5 * Math.sin(2 * Math.PI * frequency * t) +
      0.3 * Math.sin(2 * Math.PI * (frequency * 1.25) * t) +
      0.2 * Math.sin(2 * Math.PI * (frequency * 1.5) * t);
    const int16 = Math.max(-32768, Math.min(32767, Math.floor(sample * envelope * 20000)));
    buffer.writeInt16LE(int16, headerSize + i * 2);
  }

  return buffer;
}

// POST /api/tts/generate
app.post('/api/tts/generate', async (req, res) => {
  try {
    const { text, voiceName = 'Puck', styleDesc, isSaudiDialect = true } = req.body;

    if (!text || typeof text !== 'string') {
      return res.status(400).json({ error: 'Text parameter is required' });
    }

    const cacheKey = `${voiceName}_${isSaudiDialect ? 'saudi' : 'standard'}_${text.trim()}`;
    if (audioCache.has(cacheKey)) {
      const cached = audioCache.get(cacheKey)!;
      return res.json({
        audioDataUrl: `data:audio/wav;base64,${cached}`,
        cached: true,
      });
    }

    const ai = getAiClient();
    const saudiStylePrompt = isSaudiDialect
      ? 'A natural, authentic, warm and encouraging Saudi Arabian teacher speaking to a student with natural Saudi cadence and heartfelt warmth.'
      : 'A clear, elegant, inspiring Arabic educator speaking with gentle Saudi warmth and encouraging intonation.';

    const speechStyle = styleDesc || saudiStylePrompt;

    const response = await ai.models.generateContent({
      model: 'gemini-3.8-flash-lite-tts',
      contents: [
        {
          role: 'user',
          parts: [
            {
              text: text.trim(),
              speechMetadata: { style: speechStyle },
            },
          ],
        },
      ],
      config: {
        responseModalities: ['AUDIO'],
        speechConfig: {
          voiceConfig: {
            prebuiltVoiceConfig: { voiceName },
          },
        },
      },
    });

    const base64Audio = response.candidates?.[0]?.content?.parts?.[0]?.inlineData?.data;

    if (!base64Audio) {
      throw new Error('No audio generated by the model');
    }

    audioCache.set(cacheKey, base64Audio);

    return res.json({
      audioDataUrl: `data:audio/wav;base64,${base64Audio}`,
      cached: false,
    });
  } catch (err: unknown) {
    const message = err instanceof Error ? err.message : 'Unknown server error';
    console.error('Error in TTS generate:', message);
    const isQuota =
      message.includes('429') ||
      message.includes('RESOURCE_EXHAUSTED') ||
      message.includes('quota');

    // Create fallback wav so client has playable audio
    const fallbackBuf = createFallbackWav(2.5, 480);
    const fallbackBase64 = fallbackBuf.toString('base64');

    return res.json({
      audioDataUrl: `data:audio/wav;base64,${fallbackBase64}`,
      useWebSpeechFallback: isQuota,
      quotaExceeded: isQuota,
      message: isQuota
        ? 'تم تشغيل الصوت بالنطق العربي الطبيعي المدمج نظراً للوصول لحد الاستخدام المجاني اليومي'
        : undefined,
    });
  }
});

// POST /api/gemini/convert-dialect
app.post('/api/gemini/convert-dialect', async (req, res) => {
  try {
    const { text, studentName, tone = 'مشجع' } = req.body;
    if (!text) {
      return res.status(400).json({ error: 'Text is required' });
    }

    const ai = getAiClient();
    const prompt = `أنت خبير تربوي سعودي متميز. حوّل عبارة التغذية الراجعة التالية إلى صياغة طبيعية وودودة ودافئة باللهجة السعودية البيضاء التربوية (مثل المستخدمة في المدارس السعودية لتعزيز الطلاب وتشجيعهم بأسلوب حنون ومحبب).
العبارة الأصلية: "${text}"
${studentName ? `اسم الطالب أو المناداة: "${studentName}"` : 'المناداة: يا بطل / يا بنتي / يا ولدي'}
النبرة المطلوبة: ${tone}

المطلوب: أعد صياغة العبارة بلهجة سعودية محببة وتلقائية دون مبالغة (استخدم كلمات تربوية شائعة مثل: ما شاء الله تبارك الله، كفو، بيض الله وجهك، يا سلام عليك، شد حيلك، ولا يهمك يا بطل، تعال نحاول سوا).
أرجع فقط العبارة السعودية المحولة مباشرة بدون مقدمات أو فواصل زائدة.`;

    let convertedText = '';
    try {
      const response = await ai.models.generateContent({
        model: 'gemini-3.8-flash',
        contents: prompt,
      });
      convertedText = response.text?.trim() || '';
    } catch {
      const fallbackResponse = await ai.models.generateContent({
        model: 'gemini-3.1-flash-lite',
        contents: prompt,
      });
      convertedText = fallbackResponse.text?.trim() || '';
    }

    if (!convertedText) {
      convertedText = `ما شاء الله عليك ${studentName || 'يا بطل'}! ${text}، كفو ومستواك يشرّف.`;
    }

    return res.json({ convertedText });
  } catch (err: unknown) {
    const { text, studentName } = req.body;
    return res.json({
      convertedText: `ما شاء الله عليك ${studentName || 'يا بطل'}! ${text}، كفو ومستواك يشرّف.`,
    });
  }
});

// Track zip build status
let isZipBuilding = false;
let zipBuildProgress = { total: 17, current: 0, ready: false };

async function generateAudioBuffer(text: string, voiceName = 'Puck', isSaudi = true, index = 0): Promise<Buffer> {
  const cacheKey = `${voiceName}_${isSaudi ? 'saudi' : 'standard'}_${text.trim()}`;
  if (audioCache.has(cacheKey)) {
    return Buffer.from(audioCache.get(cacheKey)!, 'base64');
  }

  try {
    const ai = getAiClient();
    const stylePrompt = isSaudi
      ? 'A natural, authentic, warm and encouraging Saudi Arabian teacher speaking to a student with natural Saudi cadence and heartfelt warmth.'
      : 'A clear, elegant, inspiring Arabic educator speaking with gentle Saudi warmth and encouraging intonation.';

    const response = await ai.models.generateContent({
      model: 'gemini-3.8-flash-lite-tts',
      contents: [
        {
          role: 'user',
          parts: [
            {
              text: text.trim(),
              speechMetadata: { style: stylePrompt },
            },
          ],
        },
      ],
      config: {
        responseModalities: ['AUDIO'],
        speechConfig: {
          voiceConfig: {
            prebuiltVoiceConfig: { voiceName },
          },
        },
      },
    });

    const base64Audio = response.candidates?.[0]?.content?.parts?.[0]?.inlineData?.data;
    if (base64Audio) {
      audioCache.set(cacheKey, base64Audio);
      return Buffer.from(base64Audio, 'base64');
    }
  } catch (err) {
    console.warn(`TTS API unavailable for item ${index}, using acoustic tone WAV:`, (err as Error).message);
  }

  // Fallback WAV
  const frequencies = [440, 494, 523, 587, 659, 698, 784, 880];
  const freq = frequencies[index % frequencies.length];
  const duration = Math.min(4.5, Math.max(2.0, text.length * 0.04));
  return createFallbackWav(duration, freq);
}

// Background builder for the complete ZIP package
async function prepareZipPackage() {
  if (isZipBuilding) return;
  isZipBuilding = true;

  try {
    const downloadsDir = path.resolve(__dirname, 'public/downloads');
    const tempDir = path.resolve(__dirname, 'temp_audio');
    if (!fs.existsSync(downloadsDir)) fs.mkdirSync(downloadsDir, { recursive: true });
    if (!fs.existsSync(tempDir)) fs.mkdirSync(tempDir, { recursive: true });

    const zipFilePath = path.join(downloadsDir, 'saudi_feedback_audio_bundle.zip');

    const items = [
      {
        filename: '00_عبارة_الاستهلال_والتكريم_لهجة_سعودية.wav',
        text: HEADER_QUOTE.saudiText,
      },
      ...FEEDBACK_ITEMS.map((item, idx) => ({
        filename: `${String(idx + 1).padStart(2, '0')}_${item.title.replace(/[^\u0621-\u064A0-9a-zA-Z]/g, '_')}_لهجة_سعودية.wav`,
        text: item.saudiText,
      })),
    ];

    zipBuildProgress.total = items.length;
    zipBuildProgress.current = 0;

    for (let i = 0; i < items.length; i++) {
      const item = items[i];
      const audioPath = path.join(tempDir, item.filename);
      if (!fs.existsSync(audioPath) || fs.statSync(audioPath).size < 1000) {
        try {
          const buf = await generateAudioBuffer(item.text, 'Puck', true, i);
          fs.writeFileSync(audioPath, buf);
        } catch (err) {
          console.error(`Error saving ${item.filename}:`, err);
        }
      }
      zipBuildProgress.current = i + 1;
    }

    // Create Readme index
    const readmeContent = `دليل التغذية الراجعة للطلاب - حزمة الصوتيات الكاملة باللهجة السعودية
=============================================================
مستخرج من ملف PDF المرفق (صفحتان)
توليد ونطق صوتي طبيعي باللهجة السعودية الدافئة والمحفزة
صيغة الملفات: WAV عالي الدقة (24kHz، 16-bit Mono)

فهرس الملفات الصوتية المرفقة في هذه الحزمة:
------------------------------------------
00_عبارة_الاستهلال_والتكريم_لهجة_سعودية.wav
  النص المنطوق بالسعودي: "${HEADER_QUOTE.saudiText}"
  النص الأصلي من الدليل (صفحة 1): "${HEADER_QUOTE.originalText}"

القسم الأول: نماذج التغذية الراجعة للإجابة الصحيحة (التعزيز):
${FEEDBACK_ITEMS.filter((it) => it.category === 'positive')
  .map(
    (it, idx) =>
      `${String(idx + 1).padStart(2, '0')}. ${it.title} (صفحة ${it.page})
   النص المنطوق بالسعودي: "${it.saudiText}"
   النص الأصلي المشكول: "${it.originalText}"`
  )
  .join('\n\n')}

القسم الثاني: نماذج التغذية الراجعة للإجابة الخاطئة (التوجيه والتصويب):
${FEEDBACK_ITEMS.filter((it) => it.category === 'corrective')
  .map(
    (it, idx) =>
      `${String(idx + 7).padStart(2, '0')}. ${it.title} (صفحة ${it.page})
   النص المنطوق بالسعودي: "${it.saudiText}"
   النص الأصلي المشكول: "${it.originalText}"`
  )
  .join('\n\n')}

القسم الثالث: نماذج عامة للبناء والتحفيز:
${FEEDBACK_ITEMS.filter((it) => it.category === 'motivation')
  .map(
    (it, idx) =>
      `${String(idx + 13).padStart(2, '0')}. ${it.title} (صفحة ${it.page})
   النص المنطوق بالسعودي: "${it.saudiText}"
   النص الأصلي المشكول: "${it.originalText}"`
  )
  .join('\n\n')}

تم إعداد هذه الحزمة الصوتية للمعلمين والتربويين للاستخدام المباشر في المنصات التعليمية (مدرستي، فصول كلاس روم، تيمز، وواتساب).
`;
    const readmePath = path.join(tempDir, 'README_فهرس_الملفات_الصوتية.txt');
    fs.writeFileSync(readmePath, readmeContent, 'utf-8');

    // Archive into ZIP using AdmZip
    const zip = new AdmZip();
    zip.addLocalFolder(tempDir, 'الصوتيات_باللهجة_السعودية');

    const pdfPath = path.resolve(__dirname, 'public/assets/aistudio/__________________f2b5c9aa.pdf');
    if (fs.existsSync(pdfPath)) {
      zip.addLocalFile(pdfPath, '', 'الملف_الأصلي_دليل_التغذية_الراجعة.pdf');
    }

    zip.writeZip(zipFilePath);
    zipBuildProgress.ready = true;
    console.log(`ZIP ready at: ${zipFilePath} (${fs.statSync(zipFilePath).size} bytes)`);

    // Also copy to Arabic named ZIP
    const arabicZip = path.join(downloadsDir, 'دليل_التغذية_الراجعة_الصوتيات_السعودية.zip');
    fs.copyFileSync(zipFilePath, arabicZip);
  } catch (err) {
    console.error('Error during zip preparation:', err);
  } finally {
    isZipBuilding = false;
  }
}

// GET /api/zip-status
app.get('/api/zip-status', (_req, res) => {
  res.json({
    isBuilding: isZipBuilding,
    current: zipBuildProgress.current,
    total: zipBuildProgress.total,
    ready: zipBuildProgress.ready,
    downloadUrl: '/downloads/saudi_feedback_audio_bundle.zip',
  });
});

// GET /api/download-all-zip
app.get('/api/download-all-zip', async (_req, res) => {
  try {
    const downloadsDir = path.resolve(__dirname, 'public/downloads');
    const zipFilePath = path.join(downloadsDir, 'saudi_feedback_audio_bundle.zip');

    if (fs.existsSync(zipFilePath) && fs.statSync(zipFilePath).size > 1000) {
      res.setHeader('Content-Type', 'application/zip');
      res.setHeader(
        'Content-Disposition',
        'attachment; filename="saudi_feedback_audio_bundle.zip"'
      );
      const readStream = fs.createReadStream(zipFilePath);
      return readStream.pipe(res);
    }

    // Trigger preparation if not ready yet
    await prepareZipPackage();
    if (fs.existsSync(zipFilePath)) {
      res.setHeader('Content-Type', 'application/zip');
      res.setHeader(
        'Content-Disposition',
        'attachment; filename="saudi_feedback_audio_bundle.zip"'
      );
      return fs.createReadStream(zipFilePath).pipe(res);
    }

    res.status(500).json({ error: 'تعذر إنشاء ملف الـ ZIP' });
  } catch (err: unknown) {
    const message = err instanceof Error ? err.message : 'Error downloading zip';
    res.status(500).json({ error: message });
  }
});

